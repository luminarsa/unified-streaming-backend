
import uuid

from sqlalchemy import (
    Boolean,
    Column,
    DateTime,
    ForeignKey,
    String,
    Text,
    UniqueConstraint,
    func,
)

from sqlalchemy.dialects.postgresql import UUID, JSONB
from sqlalchemy.orm import relationship

from app.db.base import Base



class Account(Base):
    __tablename__ = "accounts"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)

    email = Column(
        String(320),
        unique=True,
        index=True,
        nullable=False,
    )

    password_hash = Column(Text, nullable=False)

    # International phone number, e.g. +27821234567.
    # Temporarily nullable to support existing accounts.
    phone_number = Column(String(20), nullable=True)

    status = Column(
        String(20),
        default="active",
        nullable=False,
    )

    # Email verification status.
    email_verified = Column(
        Boolean,
        default=False,
        server_default="false",
        nullable=False,
    )

    email_verified_at = Column(DateTime(timezone=True))

    # Referral code supplied during registration.
    referral_code_used = Column(String(15))
    # Hashed Profile Lock PIN.
    # NULL means the account has not configured a Profile Lock PIN.
    profile_lock_pin_hash = Column(
        Text,
        nullable=True,
    )
    # Encrypted Profile Lock PIN.
    # Used when the account owner needs to view their PIN.
    profile_lock_pin_encrypted = Column(
        Text,
        nullable=True,
    )
    profile_lock_pin_updated_at = Column(
        DateTime(timezone=True),
        nullable=True,
    )
    created_at = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )

    updated_at = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )

    profiles = relationship(
        "Profile",
        back_populates="account",
        cascade="all, delete-orphan",
    )

    auth_sessions = relationship(
        "AuthSession",
        back_populates="account",
        cascade="all, delete-orphan",
    )
    registered_devices = relationship(
        "RegisteredDevice",
        back_populates="account",
        cascade="all, delete-orphan",
    )
    email_verifications = relationship(
        "EmailVerification",
        back_populates="account",
        cascade="all, delete-orphan",
    )


class Profile(Base):
    __tablename__ = "profiles"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)

    account_id = Column(
        UUID(as_uuid=True),
        ForeignKey("accounts.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )

    name = Column(String(60), nullable=False)

    # Stores the avatar URL or avatar reference.
    avatar_key = Column(String(500))

    is_kids_profile = Column(
        Boolean,
        default=False,
        nullable=False,
    )

    preferences = Column(
        JSONB,
        default=dict,
        nullable=False,
    )

    created_at = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )

    updated_at = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )

    account = relationship(
        "Account",
        back_populates="profiles",
    )

class Avatar(Base):
    __tablename__ = "avatars"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    url = Column(String)
    created_at = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )


class RegisteredDevice(Base):
    __tablename__ = "registered_devices"

    id = Column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )

    account_id = Column(
        UUID(as_uuid=True),
        ForeignKey("accounts.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )

    # Persistent installation UUID generated by the frontend/native app.
    device_installation_id = Column(
        UUID(as_uuid=True),
        nullable=False,
    )

    # User-friendly device name, e.g. Living Room TV.
    device_name = Column(
        String(120),
        nullable=False,
    )
    is_name_confirmed = Column(Boolean, default=False, nullable=False)

    # android, windows, macos, browser, etc.
    device_type = Column(
        String(30),
        nullable=False,
    )

    # The profile assigned to this device.
    # NULL means the device is not profile-locked.
    locked_profile_id = Column(
        UUID(as_uuid=True),
        ForeignKey("profiles.id", ondelete="SET NULL"),
        nullable=True,
    )

    last_seen_at = Column(
        DateTime(timezone=True),
        nullable=True,
    )

    created_at = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )

    updated_at = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )

    # A single installation can have a separate device record
    # for each account that signs into it.
    __table_args__ = (
        UniqueConstraint(
            "account_id",
            "device_installation_id",
            name="uq_registered_device_account_installation",
        ),
    )

    account = relationship(
        "Account",
        back_populates="registered_devices",
    )

    locked_profile = relationship(
        "Profile",
    )


class AuthSession(Base):
    """Stores one signed-in session for an account."""

    __tablename__ = "auth_sessions"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    account_id = Column(UUID(as_uuid=True), ForeignKey("accounts.id", ondelete="CASCADE"), index=True, nullable=False)
    token_hash = Column(Text, unique=True, nullable=False)
    active_profile_id = Column(UUID(as_uuid=True), ForeignKey("profiles.id", ondelete="SET NULL"), nullable=True)
    device_name = Column(String(120))
    user_agent = Column(String(500))
    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)
    last_seen_at = Column(DateTime(timezone=True))
    expires_at = Column(DateTime(timezone=True), nullable=False)
    revoked_at = Column(DateTime(timezone=True))
    revoked_reason = Column(String(80))
    account = relationship("Account", back_populates="auth_sessions")
    active_profile = relationship("Profile")


class ProfileLockAuthorizationGrant(Base):
    __tablename__ = "profile_lock_authorization_grants"

    id = Column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )

    account_id = Column(
        UUID(as_uuid=True),
        ForeignKey("accounts.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )

    device_id = Column(
        UUID(as_uuid=True),
        ForeignKey("registered_devices.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )

    # Only the hash is stored, never the original grant.
    grant_hash = Column(
        String(64),
        unique=True,
        nullable=False,
    )

    operation = Column(
        String(40),
        nullable=False,
    )

    expires_at = Column(
        DateTime(timezone=True),
        nullable=False,
    )

    used_at = Column(
        DateTime(timezone=True),
        nullable=True,
    )

    created_at = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )

    account = relationship("Account")
    device = relationship("RegisteredDevice")
